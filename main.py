# main.py
from fastapi import FastAPI
from routers import skills, journals

# Define descriptions for each tag group (shown in /docs)
tags_metadata = [
    {
        "name": "Skills",
        "description": "Endpoints for managing your tech skills and proficiency levels.",
    },
    {
        "name": "Journals",
        "description": "Endpoints for managing your learning journal entries and linking them to skills.",
    },
    {
        "name": "Root",
        "description": "Basic API information and health checks.",
    },
]

app = FastAPI(
    title="Developer Skill Tracker API",
    description="""
    A comprehensive API for tracking your technical skills and learning progress.

    ## Features

    * **Skills Management**: Add, update, and track your proficiency in various technologies
    * **Learning Journals**: Document your learning journey with detailed notes
    * **Resource Linking**: Connect journal entries to specific skills
    * **Data Integrity**: Built-in validation prevents orphaned records

    ## Usage

    1. Create skills using `POST /skills/`
    2. Create journal entries using `POST /journals/`
    3. Link journals to skills using the `skill_id` field
    4. Filter journals by skill using `GET /journals/?skill_id=1`

    ## Important Notes

    * Skills cannot be deleted while journals are linked to them
    * Journal entries can exist without being linked to a skill (`skill_id: null`)
    * All IDs are automatically generated by the server
    """,
    version="1.0.0",
    openapi_tags=tags_metadata,
    contact={
        "name": "Skill Tracker Team",
        "email": "support@skilltracker.com"
    },
    license_info={
        "name": "MIT License",
        "url": "https://opensource.org/licenses/MIT"
    }
)

# Include routers
app.include_router(skills.router)
app.include_router(journals.router)


@app.get("/", tags=["Root"], summary="API Information")
def root():
    return {
        "message": "Welcome to the Developer Skill Tracker API",
        "version": "1.0.0",
        "documentation": "/docs",
        "endpoints": {
            "skills": "/skills",
            "journals": "/journals",
            "health": "/health"
        }
    }


@app.get("/health", tags=["Root"], summary="Health Check")
def health_check():
    return {
        "status": "healthy",
        "service": "skill-tracker-api",
        "version": "1.0.0"
    }